-- The old (Fernet, unlabeled) credential values, copied here by credentials.upgrade_credentials
-- before it seals them with their server label. Only a rollback past that release needs them
-- (docs/gitops.md, Rollback). Drop this table once no release before labels is a rollback target.
CREATE TABLE IF NOT EXISTS credential_backup_v1 (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source    TEXT NOT NULL CHECK (source IN ('servers', 'user_credentials')),
    server_id BIGINT NOT NULL,
    user_id   BIGINT,
    value     TEXT NOT NULL,
    saved_at  DOUBLE PRECISION NOT NULL
);
